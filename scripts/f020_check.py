"""F/020, "Bolting plates / Multiplication without Table": one run, or a set of patterns?

Reads mechanical/F020-plates.txt and executes its labels as persistent state
(hypothesis P: a B bolts until a U), in the order written, through all three
blocks. Reports every label that the state contradicts (a U on a part not
bolted, a B on a part already bolted), by group, and compares block 3's
product and multiplier entries with block 2's.

  python3 scripts/f020_check.py [--md OUT]
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GROUP = {**{f"f0{i}": "multiplicand" for i in range(1, 9)},
         **{f"f{i:02d}": "product" for i in range(9, 20)},
         **{f"f{i}": "multiplier" for i in range(20, 25)}}


def rows():
    for line in (ROOT / "mechanical/F020-plates.txt").read_text().splitlines():
        if re.match(r"b\d\.l\d+ ", line):
            loc, col, entry, *_ = [x.strip() for x in line.split("|")]
            yield loc, col, entry


def trace():
    st, anomalies = {}, []
    for loc, col, entry in rows():
        if not entry.startswith("label"):
            continue
        for kind, k in re.findall(r"([BU])(\d*)", entry.split('"')[1]):
            cur = st.get(col)
            if kind == "U" and cur != k:
                anomalies.append((loc, col, f"U{k}", "not bolted" if cur is None else f"bolted to {cur}"))
            if kind == "B" and cur:
                anomalies.append((loc, col, f"B{k}", f"already bolted to {cur}"))
            st[col] = None if kind == "U" else k
    return anomalies


def entries(block, lines, groups):
    out = []
    for loc, col, entry in rows():
        b, l = loc.split(".")
        if b == block and l in lines and (col.startswith("across") or GROUP.get(col.split()[0]) in groups):
            if col.startswith("across"):
                first = col.split()[1].split("-")[0]
                if GROUP.get(first) not in groups:
                    continue
            out.append((l, col, entry))
    return out


def report():
    an = trace()
    L = ["# F/020: one run, or a set of patterns?", "",
         "Generated by `python3 scripts/f020_check.py --md docs/f020-schedule.md`. F/020's labels "
         "(`mechanical/F020-plates.txt`, transcribed in `sources/notes/F018.md` §4) executed as persistent "
         "state, in the order written, through all three blocks, as if the sheet were one continuous run.", "",
         f"## 1. Labels the state contradicts: {len(an)}", "",
         "| Where | Column | Group | Label | State |", "|---|---|---|---|---|"]
    for loc, col, lab, why in an:
        L.append(f"| {loc} | {col} | {GROUP.get(col.split()[0], '?')} | {lab} | {why} |")
    b2 = [(l.replace('l3', 'X').replace('l4', 'Y').replace('l5', 'Z'), c, e)
          for l, c, e in entries("b2", ("l3", "l4", "l5"), ("product", "multiplier"))]
    b3 = [(l.replace('l3', 'X').replace('l4', 'Y').replace('l5', 'Z'), c, e)
          for l, c, e in entries("b3", ("l3", "l4", "l5"), ("product", "multiplier"))]
    def norm(xs):  # the extent of a line of words ("across f11-f15") varies with the hand; compare by group
        return sorted((l, "words" if c.startswith("across") else c, re.sub(r"\s+", " ", e).lower())
                      for l, c, e in xs)
    same = norm(b2) == norm(b3)
    m2 = entries("b2", ("l3", "l5"), ("multiplicand",))
    m3 = entries("b3", ("l3", "l5"), ("multiplicand",))
    L += ["", "## 2. Block 3 against block 2, the step and the addition after it", "",
          f"- **Product and multiplier entries** (lines 3–5 of each block: labels and \"Step up\" words): "
          f"{'identical, entry for entry' if same else 'different'} ({len(b2)} entries in block 2, {len(b3)} in block 3).",
          f"- **Multiplicand entries** of the same lines: {'identical' if norm(m2) == norm(m3) else 'different'}. "
          "Block 2 line 5 restates block 1 line 2 (\"B5, P B3, ap B4, g B4\"); block 3 line 5 continues the "
          "alternation instead (\"B6, pp B4, g1 B3\").", "",
          "## 3. Reading", "",
          "- Through all three blocks the **multiplicand** labels form one consistent run: every U undoes a B, "
          "and the giving wheel alternates one, two, one … across the block boundaries (the one contradiction in "
          "this group is ap's B4 restated at block 2 line 5, ap never being unbolted).",
          "- The **product and multiplier** entries of block 3 repeat block 2's, entry for entry. Read as a "
          "continuation they contradict the state four times (′p′p unbolted when it is not bolted, ′g2 and ′P "
          "bolted when they already are, ′g1 unbolted when it is not), and they step the product \"from one to "
          "two\" when block 2's step and \"Add to N.os two\" have left it on N.<sup>o</sup> 2.",
          "- So block 3's product and multiplier lines were not written as the continuation of block 2. Three "
          "readings remain, and the sheet does not choose between them: **a pattern restated** (the step and the "
          "addition after it written out again as a schedule, from the state at the start of a step, with the "
          "multiplicand lines carried on); **a copying slip** (block 2's lines copied where the converse was "
          "meant); or **an omitted transition** (something returning the product to N.<sup>o</sup> 1 and "
          "unbolting ′P between the blocks, with no line for it, while the multiplicand lines run on without a "
          "gap). Nothing on F/020 suggests a different architecture: its other ten operations agree with the "
          "controller.",
          "- The controller's 11 of 13 (`f-control-result.md` §4) stands as scored.", ""]
    return "\n".join(L)


if __name__ == "__main__":
    text = report()
    if "--md" in sys.argv:
        Path(sys.argv[sys.argv.index("--md") + 1]).write_text(text)
    print(text)
